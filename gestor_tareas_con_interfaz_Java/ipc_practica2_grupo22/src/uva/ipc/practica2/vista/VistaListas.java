    /**
     * Devuelve la lista seleccionada para mostrar sus tareas.
     * Evita errores en el toString
     * @return string con el nombre de la lista
     */
    public String getLista(){
        
        
       if((this.selectorListasComboBox.getSelectedItem()) != null){
           
           return this.selectorListasComboBox.getSelectedItem().toString();
           
       }else{
           
           return null;
           
       }
        
    }
    
    /**
     * Devuelve el nombre introducido para una lista nueva en el TextField.
     * Controla que no exista una lista con ese nombre y que no este vacio
     * @param listas, mapa con todas las listas
     * @return nombreLista, string con el nombre introducido
     */
    public String getNombre(HashMap<String,ArrayList<EntradaHistorial>> listas){
        
        
        String nombreLista = this.nombreListaTextField.getText();
        
        if(listas.containsKey(nombreLista)){
            
            throw new IllegalStateException("");
                      
        }else if (nombreLista.length() < 1){
            
            throw new IllegalArgumentException("");
        }else{
            
            return nombreLista;
        }
        
    }
    
