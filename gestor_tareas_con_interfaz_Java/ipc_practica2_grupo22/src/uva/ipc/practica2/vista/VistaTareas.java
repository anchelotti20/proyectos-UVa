    /**
     * Actualiza la lista para mostrar las tareas introducidas cuando se añade o se elimina una.
     * Los textos siguen un formato especifico separado por ":" para poder manejarlo
     * @param historial, arraylist con las tareas guardadas
     */
    public void actualizarHistorial(String lista, HashMap<String,ArrayList<EntradaHistorial>> historial) {
        
        String[] historialArray = new String[historial.get(lista).size()];
        int indice=0;
        
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
        String fecha;
        
        for(EntradaHistorial elem: historial.get(lista)){
            
            fecha = formato.format(elem.getFechaTarea());
            
            historialArray[indice]="Tarea:" + elem.getNombreTarea() + ":" + fecha + ":Prioridad:" + elem.getprioridadTarea() + ":" + "Porcentaje:"+ elem.getPorcentajeTarea() + ":" + elem.getCompletadaTarea();
            indice++;
            
        }
        historialList.setListData(historialArray);
       
    }
    
    /**
     * Permite modificar (actualizar) el combobox donde se almacenan las listas de las diferentes tareas
     * @param nombres , ArrayList de tipo string para los nombres de las listas
     */
    
    public void actualizarCombobox(ArrayList<String> nombres){
        
        int seleccionadaGuardar = this.elegirListaGuardarComboBox.getSelectedIndex();
        int seleccionadaMostrar = this.elegirListaMostrarComboBox.getSelectedIndex();
        
        this.elegirListaGuardarComboBox.removeAllItems();
        this.elegirListaMostrarComboBox.removeAllItems();
        
        for(String lista: nombres){
            
            this.elegirListaGuardarComboBox.addItem(lista);
            this.elegirListaMostrarComboBox.addItem(lista);
            
        }
        
        this.elegirListaGuardarComboBox.setSelectedIndex(seleccionadaGuardar);
        this.elegirListaMostrarComboBox.setSelectedIndex(seleccionadaMostrar);
        
    }
    
  /**
   * Introduce en la parte izquierda de la interfaz la informacion de la tarea que se encontraba seleccionada al pulsar editar
   * para poder editar esta informacion
   * @param nombre, string con el nombre de la tarea
   * @param descripcion, string con la descripcion de la tarea
   * @param fecha, LocalDate con la fecha de la tarea
   * @param prioridad, string con la prioridad de la tarea
   * @param porcentaje, entero que muestra el porcentaje que lleva para completarse
   * @param completada, string que si es Completada marca el checkbox
   * @param lista, string con el nombre de la lista
   */
  public void setEditar(String nombre,String descripcion, Date fecha, String prioridad, int porcentaje, String completada, String lista){
           
      this.nombreTextField.setText(nombre);
      this.descripcionTextArea.setText(descripcion);
      this.fechaDateChooser.setDate(fecha);
      
         switch (prioridad) {
             
             case "Alta":
                 
                 this.prioridadComboBox.setSelectedIndex(2);
                 break;
            
             case "Media":
                 
                 this.prioridadComboBox.setSelectedIndex(1);
                 break;
             
             default:
                 
                 this.prioridadComboBox.setSelectedIndex(0);
                 break;
         }
      
         this.porcentajeSpinner.setValue(porcentaje);
         
         if(completada.equals("Completada")){
             
             this.completadaCheckBox.setSelected(true);
         
         }else{
             
             this.completadaCheckBox.setSelected(false);
         }
         
         this.elegirListaGuardarComboBox.setSelectedItem(lista);
 
    }
  
    /**
     * Muestra la informacion de la tarea que se selecciona en el panel de informacion
     * @param nombre, string con el nombre de la tarea
     * @param descripcion, string con la descripcion de la tarea
     * @param fecha, LocalDate con la fecha de la tarea
     * @param prioridad, String con la prioridad de la tarea
     * @param porcentaje , entero que marca el poorcentaje para completarse
     */
    public void setInformacion(String nombre,String descripcion, Date fecha, String prioridad, int porcentaje){
        
        SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
        String fechaFormateada = formato.format(fecha);
        
        this.infoNombreLabel.setText(nombre);
        this.infoDescripcionTextArea.setText(descripcion);
        this.infoFechaEscritaLabel.setText(fechaFormateada);
        this.infoPrioridadEscritaLabel.setText(prioridad);
        this.porcentajeProgress.setValue(porcentaje);
     
    }
    /**
     * Permite modificar una lista seleccionada
     * @param nombre , String con el nuevo nombre
     */
    public void setListaMostrar(String nombre){
        
        this.elegirListaMostrarComboBox.setSelectedItem(nombre);
        
    }
  
  /**
   * Devuelve la tarea que esta seleccionada en la lista
   * @return string con la tarea seleccionada
   */
  public String getTareaSeleccionada(){
      
      return this.historialList.getSelectedValue();
  }
  
  /**
   * Desmarca la tarea que estaba seleccionada en la lista
   */
  public void eliminaSeleccion(){
      
      this.historialList.clearSelection();
  }
  
  /**
   * Borra todo el texto de la interfaz de guardado
   */
  public void limpiar(){
      nombreTextField.setText("");
      descripcionTextArea.setText("");
      fechaDateChooser.setDate(null);
      porcentajeSpinner.setValue(0);
      prioridadComboBox.setSelectedIndex(0);
      completadaCheckBox.setSelected(false);
  }
  
  /**
   * Borra todo el texto de la interfaz de informacion
   */
  public void limpiarPanelInfor(){
       infoNombreLabel.setText("");
       infoDescripcionTextArea.setText("");
       infoFechaEscritaLabel.setText("");
       infoPrioridadEscritaLabel.setText("");
       porcentajeProgress.setValue(0);
  }
    

    /**
     * Muestra mensajes de error cuando ocurre algun error
     * @param mensaje, string con el mensaje a mostrar
     */
    public void mostrarMensajeError(String mensaje){
        erroresLabel.setForeground(Color.red);
        erroresLabel.setText(mensaje);
    }
    
    
    

