    /**
     * Devuelve el nombre de la tarea que se encuentre en el TextField cuando se da a guardar,
     * se asegura que no tenga menos de 1 caracter ni mas de 10 y comprueba que no haya otra tarea con el mismo
     * nombre.
     * @param historial, arraylist con la lista de tareas
     * @return nombreTextField, string con el nombre de la tarea a tarves del metodo getText()
     * @throws IllegalArgumentException, si el nombre no cumple los requisitos de caracteres
     * @throws IllegalStateException, si ya hay una tarea con el mismo nombre guardada
     */
    public String getNombreTarea(HashMap<String, ArrayList<EntradaHistorial>> historial)  {
        
        boolean tareaEsta = false;
        int indice = 0;
        String nombre = nombreTextField.getText();
        String lista = getLista();
        
        if(nombre.length()<1 ||nombre.length()>10){
            
            throw new IllegalArgumentException("");
        
        }else {
            
            for(EntradaHistorial tarea: historial.get(lista)){
                
                if(tarea.getNombreTarea().equals(nombre)){
                    
                    tareaEsta = true;
                }
                indice ++;
                
            }
            
            if(tareaEsta == true){
                
                throw new IllegalStateException("");
            }
            return nombreTextField.getText();
        }
    }
    
