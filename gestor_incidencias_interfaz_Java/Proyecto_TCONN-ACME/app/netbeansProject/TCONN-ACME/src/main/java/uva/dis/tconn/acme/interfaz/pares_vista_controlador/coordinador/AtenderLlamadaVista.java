    private void btnRecibeLlamadaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRecibeLlamadaActionPerformed

        errorLabel.setText("");
        
        String telefonoString = tlfLlamada.getText();
        
        String telefonoLimpio = telefonoString.replace(" ", "");
        
        String patron = "^[6789]\\d{8}$";
        
        if(telefonoLimpio.matches(patron)){
            
            int telefono = Integer.parseInt(telefonoLimpio);
            
            controlador.procesaEventoRecibirLlamada(telefono);
            
            jLabel6.setEnabled(true);
            jLabel7.setEnabled(true);
            jLabel8.setEnabled(true);
            jLabel9.setEnabled(true);
            nContrato.setEnabled(true);
            telContrato.setEnabled(true);
            nifCif.setEnabled(true);
            btnConfirmar1.setEnabled(true);
            btnRecibeLlamada.setEnabled(false);
            tlfLlamada.setEnabled(false);
            btnSinDatos1.setEnabled(true);
            
        }else{
            
            mostrarMensajeError("Telefono incorrecto");
            
        }
        
            
        
       
        
    }//GEN-LAST:event_btnRecibeLlamadaActionPerformed

