    private void listaIncidenciasValueChanged(javax.swing.event.ListSelectionEvent evt) {// GEN-FIRST:event_listaIncidenciasValueChanged
        if (!evt.getValueIsAdjusting()) {
            boolean seleccionValida = !listaIncidencias.isSelectionEmpty();
            btnDetalles.setEnabled(seleccionValida);
        }
    }// GEN-LAST:event_listaIncidenciasValueChanged

    /**
     * Obtiene el día seleccionado
     * 
     * @return Día seleccionado.
     */
    public int getDia() {
        return Integer.parseInt((String) diaComboBox.getSelectedItem());
    }

    /**
     * Obtiene el mes seleccionado
     * 
     * @return Mes seleccionado.
     */
    public int getMes() {
        return mesComboBox.getSelectedIndex() + 1;
    }

    /**
     * Obtiene el año seleccionado
     * 
     * @return Año seleccionado.
     */
    public int getAnio() {
        return Integer.parseInt((String) anioComboBox.getSelectedItem());
    }

    /**
     * Obtiene estado seleccionado para filtrar las incidencias
     * 
     * @return Incide del estado seleccionado
     *         0: Todas
     *         1: Resuetas remotamente
     *         2: Resueltas in situ
     *         3: No resueltas
     */
    public int getEstadoSeleccionado() {
        return estadoComboBox.getSelectedIndex();
    }

    /**
     * Muestra las incidencias obtenidas en la consulta en la lista de la vista
     * 
     * @param incidencias Array con la información a mostrar de cada incidencia, con
     *                    el formato "COD - HORA - CRITICIDAD - ESTADO"
     */
    public void mostrarIncidencias(String[] incidencias) {
        listaIncidencias.setListData(incidencias);
        btnDetalles.setVisible(true);
        btnDetalles.setEnabled(false);
        lblLista.setVisible(true);
    }

    /**
     * Muestra un mensaje de error en la vista para informar al usuario
     * @param mensaje Mensaje de error a mostrar
     */
    public void mostrarMensajeError(String mensaje) {
        lblError.setText(mensaje);
    }

    private void limpiarVista() {
        diaComboBox.setSelectedIndex(0);
        mesComboBox.setSelectedIndex(0);
        anioComboBox.setSelectedIndex(0);
        estadoComboBox.setSelectedIndex(0);

        listaIncidencias.setListData(new String[0]);

        lblError.setText("");
        btnDetalles.setVisible(false);
        lblLista.setVisible(false);
    }

